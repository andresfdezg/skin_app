"""Build the HAM10000 train/val split and write a short data report.

Usage: uv run python scripts/prepare_data.py [--config configs/data_ham10000.yaml]
"""
import argparse
from pathlib import Path

import pandas as pd
from PIL import Image

from vibe_skin.config import load_config, resolve
from vibe_skin.data.ham10000 import CLASSES, load_test_metadata, load_train_metadata, make_splits


def counts_table(df: pd.DataFrame, by: str) -> pd.DataFrame:
    t = pd.crosstab(df["dx"], df[by]).reindex(CLASSES).fillna(0).astype(int)
    for col in list(t.columns):
        t[f"{col} %"] = (100 * t[col] / t[col].sum()).round(1)
    return t


def md(df: pd.DataFrame) -> str:
    return df.to_markdown() if hasattr(df, "to_markdown") else f"```\n{df}\n```"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/data_ham10000.yaml")
    args = parser.parse_args()
    cfg = load_config(args.config)

    train = load_train_metadata(cfg)
    test = load_test_metadata(cfg)

    # Integrity checks
    missing_train = train["path"].isna().sum()
    assert missing_train == 0, f"{missing_train} training images not found"
    missing_test = test.loc[test["path"].isna(), "image_id"].tolist()
    if missing_test:
        print(f"Warning: {len(missing_test)} test images listed in the CSV but not on disk: {missing_test}")
        test = test.dropna(subset=["path"])
    assert train["image_id"].is_unique
    dx_per_lesion = train.groupby("lesion_id")["dx"].nunique()
    assert (dx_per_lesion == 1).all(), "some lesions have more than one diagnosis"

    train["split"] = make_splits(train, cfg["val_fraction"], cfg["seed"])

    # Leakage checks
    lesions = train.groupby("split")["lesion_id"].apply(set)
    assert not (lesions["train"] & lesions["val"]), "lesion leakage between train and val"
    overlap_test = set(test["image_id"]) & set(train["image_id"])
    assert not overlap_test, "test images also appear in train/val"

    out = resolve(cfg["splits_file"])
    out.parent.mkdir(parents=True, exist_ok=True)
    train[["image_id", "lesion_id", "dx", "split"]].to_csv(out, index=False)
    print(f"Wrote {out.relative_to(resolve('.'))}")

    # Report
    all_df = pd.concat([train, test.assign(split="test")], ignore_index=True)
    imgs_per_lesion = train.groupby("lesion_id").size()
    sizes = pd.Series([Image.open(p).size for p in all_df["path"].sample(200, random_state=0)])

    lines = [
        "# HAM10000 data report",
        "",
        f"Generated by `scripts/prepare_data.py` with seed {cfg['seed']}.",
        "",
        "## Summary",
        "",
        f"- Train+val: {len(train)} images from {train['lesion_id'].nunique()} lesions.",
        f"- Test (official ISIC 2018 Task 3): {len(test)} images."
        + (f" Missing on disk and skipped: {', '.join(missing_test)}." if missing_test else ""),
        f"- Lesions with more than one image: {(imgs_per_lesion > 1).sum()} "
        f"({100 * (imgs_per_lesion > 1).mean():.1f}%), max {imgs_per_lesion.max()} images per lesion.",
        f"- Images grouped by lesion: no lesion appears in both train and val. Checked.",
        f"- Image sizes (sample of 200): {sizes.value_counts().to_dict()}",
        "",
        "## Class counts per split",
        "",
        md(counts_table(all_df, "split")),
        "",
        "## Diagnosis confirmation method (dx_type)",
        "",
        md(pd.crosstab(all_df["dx_type"], all_df["split"])),
        "",
        "## Age",
        "",
        md(all_df.groupby("split")["age"].describe().round(1)),
        "",
        "## Sex",
        "",
        md(pd.crosstab(all_df["sex"].fillna("missing"), all_df["split"])),
        "",
        "## Localization",
        "",
        md(pd.crosstab(all_df["localization"].fillna("missing"), all_df["split"])),
        "",
        "## Source dataset",
        "",
        md(pd.crosstab(all_df["dataset"], all_df["split"])),
        "",
    ]
    report = resolve("reports/data_ham10000.md")
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {report.relative_to(resolve('.'))}")


if __name__ == "__main__":
    main()
